  /**
   * Get the tenant's slot-generation settings (weekend days, timezone,
   * auto-generation configuration).
   */
  async getSlotSettings(tenantId: string): Promise<SlotSettingsResponse> {
    const tenant = await this.prisma.tenant.findUnique({
      where: { id: tenantId },
      select: {
        timezone: true,
        weekendDays: true,
        autoGenerateEnabled: true,
        autoGenerateDaysAhead: true,
      },
    });
    if (!tenant) {
      throw new NotFoundException('Tenant not found');
    }

    return {
      weekendDays: this.parseWeekendDays(tenant.weekendDays),
      timezone: tenant.timezone,
      autoGenerateEnabled: tenant.autoGenerateEnabled,
      autoGenerateDaysAhead: tenant.autoGenerateDaysAhead,
    };
  }

  /**
   * Update the tenant's slot-generation settings. Written to the Tenant row
   * with an audit entry in the same transaction.
   */
  async updateSlotSettings(
    tenantId: string,
    dto: UpdateSlotSettingsDto,
    userId: string,
  ): Promise<SlotSettingsResponse> {
    const existing = await this.prisma.tenant.findUnique({
      where: { id: tenantId },
      select: {
        timezone: true,
        weekendDays: true,
        autoGenerateEnabled: true,
        autoGenerateDaysAhead: true,
      },
    });
    if (!existing) {
      throw new NotFoundException('Tenant not found');
    }

    const data: Prisma.TenantUpdateInput = {};
    if (dto.weekendDays !== undefined) {
      data.weekendDays = dto.weekendDays;
    }
    if (dto.autoGenerateEnabled !== undefined) {
      data.autoGenerateEnabled = dto.autoGenerateEnabled;
    }
    if (dto.autoGenerateDaysAhead !== undefined) {
      data.autoGenerateDaysAhead = dto.autoGenerateDaysAhead;
    }

    await this.prisma.$transaction(async (tx) => {
      await tx.tenant.update({ where: { id: tenantId }, data });

      await this.createAuditLog(tx, {
        tenantId,
        userId,
        entityType: 'Tenant',
        entityId: tenantId,
        action: 'Update',
        oldValue: {
          weekendDays: existing.weekendDays,
          autoGenerateEnabled: existing.autoGenerateEnabled,
          autoGenerateDaysAhead: existing.autoGenerateDaysAhead,
        },
        newValue: {
          weekendDays: dto.weekendDays ?? existing.weekendDays,
          autoGenerateEnabled:
            dto.autoGenerateEnabled ?? existing.autoGenerateEnabled,
          autoGenerateDaysAhead:
            dto.autoGenerateDaysAhead ?? existing.autoGenerateDaysAhead,
        },
      });
    });

    return {
      weekendDays:
        dto.weekendDays ?? this.parseWeekendDays(existing.weekendDays),
      timezone: existing.timezone,
      autoGenerateEnabled:
        dto.autoGenerateEnabled ?? existing.autoGenerateEnabled,
      autoGenerateDaysAhead:
        dto.autoGenerateDaysAhead ?? existing.autoGenerateDaysAhead,
    };
  }

  /**
   * List the tenant's holiday calendar. Dates marked as holidays are priced
   * with Holiday pricing rules (or generate no slots if none exist).
   */
  async listHolidays(tenantId: string): Promise<HolidayResponse[]> {
    const holidays = await this.prisma.holiday.findMany({
      where: { tenantId },
      orderBy: { date: 'asc' },
    });
    return holidays.map((h) => ({
      id: h.id,
      tenantId: h.tenantId,
      date: this.formatDateToYYYYMMDD(h.date),
      name: h.name,
    }));
  }

  /**
   * Mark a date as a holiday. One holiday per (tenant, date) — a duplicate
   * date returns 409.
   */
  async addHoliday(
    tenantId: string,
    dto: CreateHolidayDto,
    userId: string,
  ): Promise<HolidayResponse> {
    const date = this.parseDateString(dto.date);
    if (Number.isNaN(date.getTime())) {
      throw new BadRequestException('Invalid date format');
    }

    const duplicate = await this.prisma.holiday.findFirst({
      where: { tenantId, date },
      select: { id: true },
    });
    if (duplicate) {
      throw new ConflictException('A holiday is already marked for this date');
    }

    const created = await this.prisma.$transaction(async (tx) => {
      const holiday = await tx.holiday.create({
        data: { tenantId, date, name: dto.name },
      });

      await this.createAuditLog(tx, {
        tenantId,
        userId,
        entityType: 'Holiday',
        entityId: holiday.id,
        action: 'Create',
        newValue: { date: dto.date, name: dto.name },
      });

      return holiday;
    });

    return {
      id: created.id,
      tenantId: created.tenantId,
      date: this.formatDateToYYYYMMDD(created.date),
      name: created.name,
    };
  }

  /**
   * Remove a holiday from the tenant's calendar. Future generation runs will
   * classify the date by its weekday again; already-generated slots keep
   * their price snapshots.
   */
  async removeHoliday(
    tenantId: string,
    holidayId: string,
    userId: string,
  ): Promise<{ message: string }> {
    const holiday = await this.prisma.holiday.findFirst({
      where: { id: holidayId, tenantId },
    });
    if (!holiday) {
      throw new NotFoundException('Holiday not found');
    }

    await this.prisma.$transaction(async (tx) => {
      await tx.holiday.delete({ where: { id: holidayId } });

      await this.createAuditLog(tx, {
        tenantId,
        userId,
        entityType: 'Holiday',
        entityId: holidayId,
        action: 'Delete',
        oldValue: {
          date: this.formatDateToYYYYMMDD(holiday.date),
          name: holiday.name,
        },
      });
    });

    return { message: 'Holiday removed successfully' };
  }

  /**
   * Lazily release holds whose `heldUntil` has passed. Cheaper and simpler
   * than a cron job for v1; called before every read.
   *
   * NOTE: a dedicated `@Cron` job (the task's "Option A") can be added later
   * to release holds even when the slots table is not being read.
   *
   * Public: BookingsService.getDayView calls this lazily before reading the
   * day grid, mirroring findAll/findOne here.
   */
  async releaseExpiredHolds(tenantId: string): Promise<void> {
    await this.prisma.slot.updateMany({
      where: {
        tenantId,
        status: SlotStatus.Held,
        heldUntil: { lt: new Date() },
      },
      data: {
        status: SlotStatus.Available,
        heldAt: null,
        heldBy: null,
        heldUntil: null,
      },
    });
  }

