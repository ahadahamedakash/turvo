/**
 * Slot shaped for API responses.
 * Prisma's `Decimal` price and `@db.Date`/`@db.Time` values are serialized to
 * strings (price, date as YYYY-MM-DD, times as HH:mm) to stay symmetric with
 * the Pricing module's wire format.
 */
export interface SlotResponse {
  id: string;
  tenantId: string;
  courtId: string;
  courtName?: string;
  pricingRuleId?: string;
  price: string;
  date: string;
  startTime: string;
  endTime: string;
  status: SlotStatus;
  heldAt?: Date | null;
  heldBy?: string | null;
  heldUntil?: Date | null;
  createdAt: Date;
  updatedAt: Date;
}

/**
 * Paginated slot list response
 */
export interface SlotListResponse {
  data: SlotResponse[];
  total: number;
  page: number;
  limit: number;
  totalPages: number;
}

/**
 * Result returned by slot generation.
 * `generated` = rows actually inserted; `skipped` = rows that already existed
 * (deduped by the unique constraint `no_duplicate_slot_generation`).
 */
export interface SlotGenerationResult {
  generated: number;
  skipped: number;
  errors: string[];
}

/**
 * Tenant slot-generation settings
 */
export interface SlotSettingsResponse {
  weekendDays: number[];
  timezone: string;
  autoGenerateEnabled: boolean;
  autoGenerateDaysAhead: number;
}

/**
 * Holiday calendar entry
 */
export interface HolidayResponse {
  id: string;
  tenantId: string;
  date: string;
  name: string;
}

/**
 * Prisma transaction client type (for audit-log writes inside $transaction)
 */
type PrismaTransaction = Omit<
  PrismaClient,
  '$connect' | '$disconnect' | '$on' | '$transaction' | '$use' | '$extends'
>;

/**
 * Default hold window (in minutes) when a customer starts checkout.
 */
const DEFAULT_HOLD_MINUTES = 15;

/**
 * Maximum number of days that can be generated in a single request.
 * Guards against accidentally materializing huge slot ranges.
 */
const MAX_GENERATE_RANGE_DAYS = 90;

/**
 * Allowed slot intervals (minutes) a court can be configured with.
 * Guard here as well as in the courts module so bad data can never
 * produce zero-length or nonsensical slots.
 */
const ALLOWED_SLOT_INTERVALS = [30, 45, 60, 90, 120];

/**
 * Default weekend when a tenant has no valid `weekendDays` set:
 * Friday (5) + Saturday (6) — the Bangladesh weekend.
 */
const DEFAULT_WEEKEND_DAYS = [5, 6];

/**
 * Map of short weekday names (as produced by Intl 'en-US') to ISO day numbers.
 */
const WEEKDAY_NAME_TO_INDEX: Record<string, number> = {
  Sun: 0,
  Mon: 1,
  Tue: 2,
  Wed: 3,
  Thu: 4,
  Fri: 5,
  Sat: 6,
};

