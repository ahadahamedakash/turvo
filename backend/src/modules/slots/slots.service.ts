  /**
   * Throw 404 if a tenant-scoped slot does not exist. Used to distinguish
   * "not found" from "wrong state" after a zero-row conditional update.
   */
  private async assertSlotExists(
    client: PrismaTransaction,
    slotId: string,
    tenantId: string,
  ): Promise<void> {
    const exists = await client.slot.findFirst({
      where: { id: slotId, tenantId },
    });
    if (!exists) {
      throw new NotFoundException('Slot not found');
    }
  }

  /**
   * Parse a `YYYY-MM-DD` string into a UTC-midnight Date. Pinning to UTC keeps
   * day-type determination (and the stored `@db.Date` value) deterministic
   * regardless of the server's local timezone.
   */
  private parseDateString(dateStr: string): Date {
    const [year, month, day] = dateStr.split('-').map(Number);
    return new Date(Date.UTC(year, month - 1, day));
  }

  /**
   * Format a `@db.Date` Date as `YYYY-MM-DD` using UTC getters.
   */
  private formatDateToYYYYMMDD(date: Date): string {
    const year = date.getUTCFullYear();
    const month = (date.getUTCMonth() + 1).toString().padStart(2, '0');
    const day = date.getUTCDate().toString().padStart(2, '0');
    return `${year}-${month}-${day}`;
  }

  /**
   * Format a `@db.Time` Date as `HH:mm` using UTC getters (symmetric with
   * parseTimeString).
   */
  private formatTimeToHHmm(date: Date): string {
    const hours = date.getUTCHours().toString().padStart(2, '0');
    const minutes = date.getUTCMinutes().toString().padStart(2, '0');
    return `${hours}:${minutes}`;
  }

  /**
   * Iterate every UTC day in an inclusive [start, end] range.
   */
  private eachDay(start: Date, end: Date): Date[] {
    const days: Date[] = [];
    const MS_PER_DAY = 24 * 60 * 60 * 1000;
    for (let t = start.getTime(); t <= end.getTime(); t += MS_PER_DAY) {
      days.push(new Date(t));
    }
    return days;
  }

  /**
   * Determine the day type for a date, in priority order:
   *   1. Holiday — the date is in the tenant's holiday calendar
   *   2. Weekend — the date's weekday (in the TENANT's timezone) is one of the
   *      tenant's configured weekend days (default Fri + Sat for Bangladesh)
   *   3. Weekday
   *
   * The weekday is evaluated by probing the date at 12:00 UTC — noon UTC falls
   * on the same calendar date in every real timezone — and formatting it in
   * the tenant's timezone, so classification matches the tenant's local
   * calendar rather than the server's.
   */
  private getDayType(
    date: Date,
    weekendDays: number[],
    holidayDates: Set<string>,
    timezone: string,
  ): DayType {
    const dateStr = this.formatDateToYYYYMMDD(date);

    if (holidayDates.has(dateStr)) {
      return DayType.Holiday;
    }

    const probe = new Date(`${dateStr}T12:00:00Z`);
    const weekdayName = this.getWeekdayFormatter(timezone).format(probe);
    const weekdayIndex = WEEKDAY_NAME_TO_INDEX[weekdayName] ?? -1;

    if (weekendDays.includes(weekdayIndex)) {
      return DayType.Weekend;
    }
    return DayType.Weekday;
  }

  /**
   * Intl weekday formatters cached per timezone (building an Intl formatter
   * is expensive; generation classifies many dates per call).
   */
  private readonly weekdayFormatters = new Map<string, Intl.DateTimeFormat>();

  private getWeekdayFormatter(timezone: string): Intl.DateTimeFormat {
    let formatter = this.weekdayFormatters.get(timezone);
    if (!formatter) {
      formatter = new Intl.DateTimeFormat('en-US', {
        timeZone: timezone,
        weekday: 'short',
      });
      this.weekdayFormatters.set(timezone, formatter);
    }
    return formatter;
  }

  /**
   * Parse the tenant's `weekendDays` JSON value into ISO weekday ints.
   * Falls back to the Bangladesh weekend (Fri + Sat) on any invalid value.
   */
  private parseWeekendDays(raw: unknown): number[] {
    if (Array.isArray(raw)) {
      const days = raw.filter(
        (d): d is number =>
          typeof d === 'number' && Number.isInteger(d) && d >= 0 && d <= 6,
      );
      if (days.length > 0) {
        return days;
      }
    }
    return DEFAULT_WEEKEND_DAYS;
  }

  /**
   * Current calendar date (YYYY-MM-DD) as experienced in the given timezone.
   * 'en-CA' locale formats as YYYY-MM-DD.
   */
  private todayInTimezone(timezone: string): string {
    return new Intl.DateTimeFormat('en-CA', {
      timeZone: timezone,
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
    }).format(new Date());
  }

  /**
   * Add whole days to a YYYY-MM-DD string (UTC arithmetic; date-only values
   * have no DST concerns).
   */
  private addDaysToDateString(dateStr: string, days: number): string {
    const date = this.parseDateString(dateStr);
    date.setUTCDate(date.getUTCDate() + days);
    return this.formatDateToYYYYMMDD(date);
  }

  /**
   * Expand a pricing rule's [startTime, endTime] into consecutive
   * fixed-interval slots (e.g. 60, 90 or 120 minutes). A trailing partial
   * window is dropped: the last slot only exists if it fits fully inside the
   * rule window. `endTime` is an exclusive upper bound, matching how the
   * Pricing module stores inclusive end times (including the +24h midnight
   * case, which is already resolved by the time it is read back).
   */
  private generateIntervalSlots(
    ruleStartTime: Date,
    ruleEndTime: Date,
    intervalMinutes: number,
  ): Array<{ startTime: Date; endTime: Date }> {
    const slots: Array<{ startTime: Date; endTime: Date }> = [];
    const step = intervalMinutes * 60 * 1000;
    const startMs = ruleStartTime.getTime();
    const endMs = ruleEndTime.getTime();

    for (let t = startMs; t + step <= endMs; t += step) {
      slots.push({ startTime: new Date(t), endTime: new Date(t + step) });
    }

    return slots;
  }

  /**
   * Transform a Prisma slot (with optional court name) into the API shape.
   */
  private transformSlot(
    slot: Slot & { court?: { name: string } | null },
  ): SlotResponse {
    const { court, ...data } = slot;
    return {
      id: data.id,
      tenantId: data.tenantId,
      courtId: data.courtId,
      courtName: court?.name ?? undefined,
      pricingRuleId: data.pricingRuleId ?? undefined,
      price: data.price.toString(),
      date: this.formatDateToYYYYMMDD(data.date),
      startTime: this.formatTimeToHHmm(data.startTime),
      endTime: this.formatTimeToHHmm(data.endTime),
      status: data.status,
      heldAt: data.heldAt,
      heldBy: data.heldBy,
      heldUntil: data.heldUntil,
      createdAt: data.createdAt,
      updatedAt: data.updatedAt,
    };
  }

  /**
   * Write an audit-log row using the provided transaction client.
   */
  private async createAuditLog(
    tx: PrismaTransaction,
    data: {
      tenantId: string;
      userId: string;
      entityType: string;
      entityId: string;
      action: string;
      oldValue?: Record<string, unknown>;
      newValue?: Record<string, unknown>;
    },
  ): Promise<void> {
    await tx.auditLog.create({
      data: {
        tenantId: data.tenantId,
        userId: data.userId,
        entityType: data.entityType as any,
        entityId: data.entityId,
        action: data.action as any,
        oldValue: data.oldValue as Prisma.InputJsonValue,
        newValue: data.newValue as Prisma.InputJsonValue,
      },
    });
  }
